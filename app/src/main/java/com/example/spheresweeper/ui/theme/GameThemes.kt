/**
 * Soft lighting of the pastel themes: high ambient light and little modelling, so that the cells read
 * as paper and watercolour rather than glossy plastic. The revealed-cell terms are parameters because a
 * dark theme needs them lower (see [DUSK_LIGHTING]).
 */
private fun pastelLighting(
    revealedFlat: Float = 0.86f,
    revealedLit: Float = 0.16f,
    revealedSheen: Float = 0.04f,
): SphereLighting = SphereLighting(
    ambient = 0.62f,
    diffuse = 0.42f,
    coveredFlat = 0.78f,
    coveredLit = 0.28f,
    coveredGloss = 0.1f,
    rim = Rgb.BLACK,
    revealedFlat = revealedFlat,
    revealedLit = revealedLit,
    revealedSheen = revealedSheen,
    revealedLift = Rgb.BLACK,
    oceanFlat = 0.9f,
    oceanLit = 0.2f,
    oceanSheen = 0.08f,
    oceanGlint = 0.1f,
    oceanJitter = 0.12f,
    oceanGlossTint = Rgb(1f, 1f, 1f),
    oceanRim = Rgb.BLACK,
)

private val PASTEL_LIGHTING = pastelLighting()

/**
 * Pastel lighting for light digits on dark revealed cells. Brighter shading would lower the contrast of
 * the digits, so the revealed cells get no sheen and a slightly lower flat part. The dusk theme draws
 * its gloss over the digits; at full light and full gloss every number colour, the far colour and the
 * line colour of the dusk theme stay above 4.5:1 against the revealed cell.
 */
private val DUSK_LIGHTING = pastelLighting(revealedFlat = 0.82f, revealedSheen = 0f)

/**
 * Ball palette of a pastel theme. The defaults fit a light theme: paper-coloured revealed cells with
 * dark numbers and no digit shadow, light outlines around icons, a soft shadow under the ball and a
 * faint white halo and gloss. The gloss lies under the digits, which keeps dark digits at their
 * contrast against the cell.
 */
private fun pastelSphere(
    covered: List<Long>,
    revealed: Long,
    border: Long,
    ocean: Pair<Long, Long>,
    numbers: List<Long>,
    ink: Long,
    far: Long,
    line: Long,
    wallCore: Long,
    wallGlow: Long,
    hint: Long,
    lock: Long,
    flag: Long,
    pole: Long,
    portals: List<Long>,
    core: List<Long>,
    borderAlpha: Float = 0.55f,
    lockText: Long = revealed,
    digitShadow: Long = ink,
    digitShadowAlpha: Float = 0f,
    decalOutline: Long = revealed,
    decalOutlineAlpha: Float = 0.6f,
    lostMineCell: Long = 0xFFB0B3BA,
    detonatedCell: Long = 0xFFA0605B,
    wrongFlagCell: Long = 0xFFD4A9A3,
    wrongFlag: Long = 0xFF7D8089,
    wrongPole: Long = 0xFF6A6D75,
    confetti: List<Long> = listOf(0xFFD9B26A, 0xFF8FB89A, 0xFF8FB0D0, 0xFFB49ACB, 0xFFD79AB0, 0xFFD98C7A),
    halo: Long = 0xFFFFFFFF,
    haloAlpha: Float = 0.35f,
    pool: Long = 0x38282846,
    glossAlpha: Float = 0.22f,
    decalsOverGloss: Boolean = true,
    win: Pair<Long, Long> = 0xFFE8C77A to 0xFF9BC4A0,
    lighting: SphereLighting = PASTEL_LIGHTING,
): SpherePalette = SpherePalette(
    covered = covered.map { Rgb.hex(it) },
    revealed = Rgb.hex(revealed),
    revealedDesaturation = 0f,
    revealedSwatch = argb(revealed),
    lighting = lighting,
    border = withAlpha(border, borderAlpha),
    oceanSouth = Rgb.hex(ocean.first),
    oceanNorth = Rgb.hex(ocean.second),
    numbers = IntArray(numbers.size + 1) { if (it == 0) argb(ink) else argb(numbers[it - 1]) },
    digitShadow = argb(digitShadow),
    digitShadowAlpha = digitShadowAlpha,
    decalOutline = argb(decalOutline),
    decalOutlineAlpha = decalOutlineAlpha,
    far = argb(far),
    line = argb(line),
    wallCore = argb(wallCore),
    wallGlow = argb(wallGlow),
    hint = argb(hint),
    lock = argb(lock),
    lockText = argb(lockText),
    flag = argb(flag),
    pole = argb(pole),
    wrongFlag = argb(wrongFlag),
    wrongPole = argb(wrongPole),
    mine = argb(ink),
