    /** The theme of a fresh install and of an unknown stored identifier. */
    val default: GameTheme get() = all.first()

    /** Theme with identifier [id], or [default] for null or an unknown identifier. */
    fun byId(id: String?): GameTheme = all.firstOrNull { it.id == id } ?: default
