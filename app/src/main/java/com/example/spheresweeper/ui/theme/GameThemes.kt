    mineHighlight = argb(0x8CFFFFFF),
    explodedCell = Rgb.hex(0xFFC9655C),
    detonatedCell = Rgb.hex(detonatedCell),
    lostMineCell = Rgb.hex(lostMineCell),
    wrongFlagCell = Rgb.hex(wrongFlagCell),
    tint = argb(0xFFC4605A),
    portals = IntArray(portals.size) { argb(portals[it]) },
    confetti = IntArray(confetti.size) { argb(confetti[it]) },
    halo = intArrayOf(
        withAlpha(halo, haloAlpha), withAlpha(halo, haloAlpha), withAlpha(halo, haloAlpha * 0.5f), withAlpha(halo, 0f),
    ),
    pool = intArrayOf(argb(pool), withAlpha(pool, 0f)),
    core = IntArray(3) { argb(core[it]) },
    gloss = intArrayOf(
        withAlpha(0xFFFFFFFF, glossAlpha), withAlpha(0xFFFFFFFF, glossAlpha * 0.3f), withAlpha(0xFFFFFFFF, 0f),
    ),
    decalsOverGloss = decalsOverGloss,
    win = intArrayOf(
